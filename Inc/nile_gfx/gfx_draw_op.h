#ifndef NILE_GFX_DRAW_OP_H_
#define NILE_GFX_DRAW_OP_H_

#include "nile_gfx/gfx_stdtypes.h"

enum {
	// ========== CR1 ==========
	// Control register 1

	//Primitive type
	NILE_GFX_DRAW_OP_CR1_PRIMTYPE_POS = 0,
	NILE_GFX_DRAW_OP_CR1_PRIMTYPE_MASK = 0x0F << NILE_GFX_DRAW_OP_CR1_PRIMTYPE_POS,
	NILE_GFX_DRAW_OP_CR1_PRIMTYPE_NONE = 0 << NILE_GFX_DRAW_OP_CR1_PRIMTYPE_POS, //dummy operation
	NILE_GFX_DRAW_OP_CR1_PRIMTYPE_LINE = 1 << NILE_GFX_DRAW_OP_CR1_PRIMTYPE_POS, //a pixel line
	NILE_GFX_DRAW_OP_CR1_PRIMTYPE_RECT = 2 << NILE_GFX_DRAW_OP_CR1_PRIMTYPE_POS, //a filled rectangle
	NILE_GFX_DRAW_OP_CR1_PRIMTYPE_TEXTURE = 3 << NILE_GFX_DRAW_OP_CR1_PRIMTYPE_POS, //a texture

	//Blend mode
	NILE_GFX_DRAW_OP_CR1_BLM_POS = 4,
	NILE_GFX_DRAW_OP_CR1_BLM_MASK = 0x03 << NILE_GFX_DRAW_OP_CR1_BLM_POS,
	NILE_GFX_DRAW_OP_CR1_BLM_NONE = 0 << NILE_GFX_DRAW_OP_CR1_BLM_POS, //no blending
	NILE_GFX_DRAW_OP_CR1_BLM_TGT = 1 << NILE_GFX_DRAW_OP_CR1_BLM_POS, //blend with target
	NILE_GFX_DRAW_OP_CR1_BLM_EXT = 2 << NILE_GFX_DRAW_OP_CR1_BLM_POS, //blend with external resource

	//Configuration error flag
	NILE_GFX_DRAW_OP_CR1_CERR_POS = 6,
	NILE_GFX_DRAW_OP_CR1_CERR_MASK = 0x01 << NILE_GFX_DRAW_OP_CR1_CERR_POS,
	NILE_GFX_DRAW_OP_CR1_CERR = 1 << NILE_GFX_DRAW_OP_CR1_CERR_POS,

	//Special targets
	NILE_GFX_DRAW_OP_CR1_STGT_POS = 8,
	NILE_GFX_DRAW_OP_CR1_STGT_MASK = 0x0F << NILE_GFX_DRAW_OP_CR1_STGT_POS,
	NILE_GFX_DRAW_OP_CR1_STGT_NONE = 0 << NILE_GFX_DRAW_OP_CR1_STGT_POS,
	NILE_GFX_DRAW_OP_CR1_STGT_FB0 = 1 << NILE_GFX_DRAW_OP_CR1_STGT_POS,
	NILE_GFX_DRAW_OP_CR1_STGT_FB1 = 2 << NILE_GFX_DRAW_OP_CR1_STGT_POS,
	NILE_GFX_DRAW_OP_CR1_STGT_CACHE = 3 << NILE_GFX_DRAW_OP_CR1_STGT_POS,
	NILE_GFX_DRAW_OP_CR1_STGT_LIVE_DRAW_FB = 4 << NILE_GFX_DRAW_OP_CR1_STGT_POS,

	//Special sources
	NILE_GFX_DRAW_OP_CR1_SSRC_POS = 12,
	NILE_GFX_DRAW_OP_CR1_SSRC_MASK = 0x0F << NILE_GFX_DRAW_OP_CR1_SSRC_POS,
	NILE_GFX_DRAW_OP_CR1_SSRC_NONE = 0 << NILE_GFX_DRAW_OP_CR1_SSRC_POS,
	NILE_GFX_DRAW_OP_CR1_SSRC_DISPLAYFB = 1 << NILE_GFX_DRAW_OP_CR1_SSRC_POS, //display buffer


	// ========== P1R ==========
	// Point 1 register
	NILE_GFX_DRAW_OP_P1R_XPOS_POS = 0,
	NILE_GFX_DRAW_OP_P1R_XPOS_MASK = 0xFFFF << NILE_GFX_DRAW_OP_P1R_XPOS_POS,
	NILE_GFX_DRAW_OP_P1R_YPOS_POS = 16,
	NILE_GFX_DRAW_OP_P1R_YPOS_MASK = 0xFFFF << NILE_GFX_DRAW_OP_P1R_YPOS_POS,

	// ========== P2R ==========
	// Point 2 register
	NILE_GFX_DRAW_OP_P2R_XPOS_POS = 0,
	NILE_GFX_DRAW_OP_P2R_XPOS_MASK = 0xFFFF << NILE_GFX_DRAW_OP_P2R_XPOS_POS,
	NILE_GFX_DRAW_OP_P2R_YPOS_POS = 16,
	NILE_GFX_DRAW_OP_P2R_YPOS_MASK = 0xFFFF << NILE_GFX_DRAW_OP_P2R_YPOS_POS,

	// ========== EXTRR ==========
	// External resource register
	NILE_GFX_DRAW_OP_EXTRR_RADDR_POS = 0, //resource address (e.g. texture address)
	NILE_GFX_DRAW_OP_EXTRR_RADDR_MASK = 0xFFFFFFFF << NILE_GFX_DRAW_OP_EXTRR_RADDR_POS,

	// ========== COLR ==========
	// Color register
	NILE_GFX_DRAW_OP_COLR_ARGB8888_POS = 0, //resource address (e.g. texture address)
	NILE_GFX_DRAW_OP_COLR_ARGB8888_MASK = 0xFFFFFFFF << NILE_GFX_DRAW_OP_COLR_ARGB8888_POS,
	NILE_GFX_DRAW_OP_COLR_ALPHA_MASK = 0xFF000000 << NILE_GFX_DRAW_OP_COLR_ARGB8888_POS,
	NILE_GFX_DRAW_OP_COLR_RED_MASK = 0x00FF0000 << NILE_GFX_DRAW_OP_COLR_ARGB8888_POS,
	NILE_GFX_DRAW_OP_COLR_GREEN_MASK = 0x0000FF00 << NILE_GFX_DRAW_OP_COLR_ARGB8888_POS,
	NILE_GFX_DRAW_OP_COLR_BLUE_MASK = 0x000000FF << NILE_GFX_DRAW_OP_COLR_ARGB8888_POS,

};

typedef struct {
	uint32_t CR1;
	union {
		uint32_t P1R;
		struct {
			uint16_t P1X;
			uint16_t P1Y;
		};
	};
	union {
		uint32_t P2R;
		struct {
			uint16_t P2X;
			uint16_t P2Y;
		};
	};
	union {
		uint32_t EXTRR;
		union{
			uint32_t COLR;
			struct{
				uint8_t COL_B;
				uint8_t COL_G;
				uint8_t COL_R;
				uint8_t COL_A;
			};
		};
	};
} nile_gfx_draw_op;

#endif /* NILE_GFX_DRAW_OP_H_ */
